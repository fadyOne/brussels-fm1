#!/usr/bin/env python3
"""Turns the redrawn Piknik Electronik logo (tools/gen_piknik_logo_vec.py, the one we validated) into firmware/src/ui_logo.h:
  PIK_LOGO_RUNS  the logo filled, 1-bit runs (row, x, length), drawn in one ink by logo_draw (ECO)
  PIK_EDGE_RUNS  only its outline, runs (row, x, length, heat), drawn in the beings' heat ramp by vx_logo_outline (EDIT > KIT)
No image decoding on the device. Usage: python3 tools/gen_piknik_logo.py  (needs Pillow)"""
import os, sys
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_piknik_logo_vec as V

OUT = os.path.join(HERE, "..", "firmware", "src", "ui_logo.h")
W = 160                                   # px: the logo's width on the 240 px screen
HEAT_LO, HEAT_HI = 70, 235                # the ramp's blue -> yellow, as on the planche (no cream: it does not read on white)

ink_src = V.render()                      # 500 x 500, ink = white
im = ImageOps.invert(ink_src)             # ink = dark, as the logo file
bbox = ImageOps.invert(im).getbbox()      # crop the white margins
im = im.crop(bbox)
h = round(im.height * W / im.width)
im = im.resize((W, h), Image.LANCZOS).point(lambda v: 0 if v < 140 else 255)

def ink(x, y):
    return 0 <= x < W and 0 <= y < h and im.getpixel((x, y)) == 0

runs = []
for y in range(h):
    x = 0
    while x < W:
        if ink(x, y):
            x0 = x
            while x < W and ink(x, y):
                x += 1
            runs.append((y, x0, x - x0))
        else:
            x += 1

edge = []
for y in range(h):
    x = 0
    while x < W:
        e = ink(x, y) and not (ink(x - 1, y) and ink(x + 1, y) and ink(x, y - 1) and ink(x, y + 1))
        if e:
            x0 = x
            while x < W and ink(x, y) and not (ink(x - 1, y) and ink(x + 1, y) and ink(x, y - 1) and ink(x, y + 1)):
                x += 1
            heat = HEAT_LO + (HEAT_HI - HEAT_LO) * (x0 + (x - x0) / 2) / (W - 1)
            edge.append((y, x0, x - x0, int(round(heat))))
        else:
            x += 1

body = "\n".join("    {%d,%d,%d}," % r for r in runs)
ebody = "\n".join("    {%d,%d,%d,%d}," % r for r in edge)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* generated by tools/gen_piknik_logo.py from tools/gen_piknik_logo_vec.py (the redrawn logo): do not edit */\n")
    f.write("#pragma once\n")
    f.write("#define PIK_LOGO_W %d\n#define PIK_LOGO_H %d\n" % (W, h))
    f.write("static const uint8_t PIK_LOGO_RUNS[][3] = {   /* row, x, length: the ink */\n%s\n};\n" % body)
    f.write("static const uint16_t PIK_LOGO_N = %d;\n" % len(runs))
    f.write("static const uint8_t PIK_EDGE_RUNS[][4] = {   /* row, x, length, heat: the outline */\n%s\n};\n" % ebody)
    f.write("static const uint16_t PIK_EDGE_N = %d;\n" % len(edge))
    f.write("""/* the logo centred at (cx, y) in ink c (a theme token, or a colour) */
static void logo_draw(int32_t cx, int32_t y, uint16_t c)
{
    uint16_t i;
    int32_t x0 = cx - PIK_LOGO_W / 2;
    for (i = 0; i < PIK_LOGO_N; i++)
        cv_rect(x0 + PIK_LOGO_RUNS[i][1], y + PIK_LOGO_RUNS[i][0], PIK_LOGO_RUNS[i][2], 1, c);
}
""")
print("logo %dx%d, %d ink runs, %d edge runs" % (W, h, len(runs), len(edge)))
